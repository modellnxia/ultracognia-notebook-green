class TestThemeBackgroundMustBeDark:
    """Guardrail 2026-08-21 — ver FEWSHOT_RULEBOOK.md: nenhum dos 59 exemplos
    de referência tem fundo principal claro, então isso é validado de
    verdade, não só pedido no prompt (fecha o bug de fundo quase-branco)."""

    @pytest.mark.parametrize("background", ["#FFFFFF", "#F5F5F5", "#EEEEEE", "#fff"])
    def test_rejects_light_backgrounds(self, background):
        with pytest.raises(ValidationError, match="claro demais"):
            Theme(
                palette={"primary": "#1A2B3C", "background": background, "text": "#111111"},
                font_stack="Inter",
            )

    @pytest.mark.parametrize(
        "background", ["#0D1B2E", "#0A0A0D", "#141F2E", "#1a0e0e", "#0f2418"]
    )
    def test_accepts_a_range_of_dark_hues(self, background):
        # a IA continua livre pra escolher QUALQUER matiz escuro — não é 1
        # cor fixa, é uma faixa de luminância (ver models.py).
        theme = Theme(
            palette={"primary": "#3B82F6", "background": background, "text": "#F2F2F2"},
            font_stack="Inter",
        )
        assert theme.palette["background"] == background

    def test_rejects_invalid_hex(self):
        with pytest.raises(ValidationError, match="não é um hex válido"):
            Theme(
                palette={"primary": "#1A2B3C", "background": "not-a-color", "text": "#111"},
                font_stack="Inter",
            )

    def test_accepts_light_background_when_guardrail_disabled_via_context(self):
        """
        Tarefa 1 (2026-08-21): checkbox desligado na tela = editorial pode
        ter paleta própria, mesmo clara — o contexto de validação
        (`enforce_dark_background=False`, propagado por `structure.py` via
        `DeckSpec.model_validate(data, context=...)`) desliga esse guardrail
        especificamente. Sem contexto (`model_validate` sem `context=`, ou
        construção direta `Theme(...)`), o guardrail continua ativo —
        retrocompatível com todo o resto do código.
        """
        theme = Theme.model_validate(
            {"palette": {"primary": "#1A2B3C", "background": "#F8FAFC", "text": "#111111"}, "font_stack": "Inter"},
            context={"enforce_dark_background": False},
        )
        assert theme.palette["background"] == "#F8FAFC"

    def test_still_rejects_light_background_when_context_explicitly_true(self):
        with pytest.raises(ValidationError, match="claro demais"):
            Theme.model_validate(
                {"palette": {"primary": "#1A2B3C", "background": "#FFFFFF", "text": "#111"}, "font_stack": "Inter"},
                context={"enforce_dark_background": True},
            )

    def test_rejects_light_background_when_no_context_passed_at_all(self):
        # comportamento padrão de sempre — nenhum código antigo que chama
        # Theme(...)/model_validate(...) sem `context=` deve mudar de
        # comportamento com essa mudança.
        with pytest.raises(ValidationError, match="claro demais"):
            Theme.model_validate(
                {"palette": {"primary": "#1A2B3C", "background": "#FFFFFF", "text": "#111"}, "font_stack": "Inter"}
            )


class TestThemeBackgroundAndPrimaryMustBeDistinguishable:
    """
    Achado real em produção (2026-08-21 (7)): a IA escolheu background=#081421
    e primary=#0A192F — quase idênticos (contraste 1.05:1). O CSS usa
    `primary` como cor de TEXTO nos slides de tela cheia (cover/section-break/
    closing invertem fundo↔primary) — ficou ilegível. Diferente do guardrail
    de fundo escuro (opinião de estilo, gated pelo checkbox), este é garantia
    de renderização legível — sempre ativo, com ou sem contexto.
    """

    def test_rejects_near_identical_background_and_primary(self):
        with pytest.raises(ValidationError, match="contraste baixo demais"):
            Theme(
                palette={"primary": "#0A192F", "background": "#081421", "text": "#F2F2F2"},
                font_stack="Inter",
            )

    def test_accepts_sufficiently_distinct_colors(self):
        theme = Theme(
            palette={"primary": "#3B82F6", "background": "#0D1B2E", "text": "#F2F2F2"},
            font_stack="Inter",
        )
        assert theme.palette["primary"] == "#3B82F6"

    def test_stays_active_even_when_dark_background_guardrail_is_disabled(self):
        """Não é opinião de estilo — não é desligado pelo checkbox (diferente de background_must_be_dark)."""
        with pytest.raises(ValidationError, match="contraste baixo demais"):
            Theme.model_validate(
                {
                    "palette": {"primary": "#0A192F", "background": "#081421", "text": "#F2F2F2"},
                    "font_stack": "Inter",
                },
                context={"enforce_dark_background": False},
            )

    def test_does_not_duplicate_error_when_hex_already_invalid(self):
        # background_must_be_dark já pega hex inválido antes — não deve chegar aqui
        with pytest.raises(ValidationError, match="não é um hex válido"):
            Theme(
                palette={"primary": "#0A192F", "background": "not-a-color", "text": "#111"},
                font_stack="Inter",
            )


