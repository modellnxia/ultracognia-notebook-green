class TestSlideIdUniqueness:
    def test_rejects_duplicate_slide_ids(self):
        with pytest.raises(ValidationError):
            DeckSpec(
                theme=_valid_theme(),
                slides=[
                    Slide(id="a", layout=LayoutId.COVER, title="X"),
                    Slide(id="a", layout=LayoutId.CLOSING, title="Y"),
                ],
            )

    def test_allows_distinct_slide_ids(self):
        spec = DeckSpec(
            theme=_valid_theme(),
            slides=[
                Slide(id="a", layout=LayoutId.COVER, title="X"),
                Slide(id="b", layout=LayoutId.CLOSING, title="Y"),
            ],
        )
        assert len(spec.slides) == 2


