def _valid_theme() -> Theme:
    return Theme(
        palette={"primary": "#3B82F6", "background": "#0D1B2E", "text": "#F2F2F2"},
        font_stack="Inter, system-ui, sans-serif",
    )


class TestDeckSpecValid:
    def test_accepts_minimal_valid_deck(self):
        spec = DeckSpec(
            theme=_valid_theme(),
            slides=[Slide(layout=LayoutId.COVER, title="Título")],
        )
        assert len(spec.slides) == 1
        assert spec.version == "1.0"

    def test_context_propagates_from_deckspec_to_nested_theme_validator(self):
        """
        Caminho real de produção: `structure.py::generate_deck_structure`
        chama `DeckSpec.model_validate(data, context=...)` no nível raiz —
        precisa propagar pro validador de `Theme`, aninhado dentro dele.
        """
        data = {
            "theme": {
                "palette": {"primary": "#1A2B3C", "background": "#F8FAFC", "text": "#111111"},
                "font_stack": "Inter",
            },
            "slides": [{"layout": "cover", "title": "X"}],
        }
        spec = DeckSpec.model_validate(data, context={"enforce_dark_background": False})
        assert spec.theme.palette["background"] == "#F8FAFC"

        with pytest.raises(ValidationError, match="claro demais"):
            DeckSpec.model_validate(data)  # sem context — guardrail continua ativo

    def test_slide_id_autogenerated_when_omitted(self):
        s1 = Slide(layout=LayoutId.COVER, title="A")
        s2 = Slide(layout=LayoutId.COVER, title="B")
        assert s1.id != s2.id


